from django.contrib.sitemaps import Sitemap
from .models import Post



# الـ Sitemap هي "خريطة الكنز" التي نقدمها لمحركات البحث (مثل جوجل).
# وظيفتها الأساسية: بدل أن ننتظر جوجل ليدور في موقعنا ويحاول تخمين الروابط،
# نحن نعطيه ملف XML جاهز يحتوي على قائمة منظمة بكل المقالات المنشورة لدينا،
# ونخبره أيضاً: "هذا المقال مهم جداً" (priority) و "هذا المقال قمنا بتعديله بالأمس" (lastmod).
# باختصار: هي جسر التواصل التقني الذي يضمن أرشفة مدونتك بسرعة ودقة.


class PostSitemap(Sitemap):
    # 'changefreq' تخبر محركات البحث كم مرة يتغير محتوى المقال (يومي، أسبوعي، شهري)
    changefreq = "weekly"

    # 'priority' تحدد أهمية صفحات المقالات بالنسبة لصفحات الموقع الأخرى (من 0.1 إلى 1.0)
    priority = 0.9

    def items(self):
        """
        هذه الدالة تحدد قائمة الكائنات (Objects) التي ستظهر في الخريطة.
        نستخدم الفلتر لجلب المقالات المنشورة فقط (Status.PUBLISHED أو 'PB').
        """
        return Post.objects.filter(status=Post.Status.PUBLISHED)

    def lastmod(self, obj):
        """
        تأخذ كل مقال (obj) وتُرجع تاريخ آخر تعديل له.
        يساعد هذا جوجل على معرفة ما إذا كان المقال يحتاج لإعادة أرشفة.
        """
        return obj.updated


